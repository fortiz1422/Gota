test('account archive cancellation restores focus and busy confirmation cannot close', async ({ page }) => {
  await mockAPI(page)
  let release!: () => void
  const pending = new Promise<void>(resolve => { release = resolve })
  await page.route('**/api/accounts/fixture-bank', async route => {
    if (route.request().method() !== 'DELETE') return route.fallback()
    await pending
    await route.fulfill({ json: {} })
  })
  await page.goto('/ui-exploration/forms-baseline/account-edit')
  const trigger = page.locator('[data-account-edit-archive]')
  await trigger.click()
  const confirmation = page.locator('[data-confirmation-surface]')
  await confirmation.getByRole('button', { name: 'Cancelar', exact: true }).click()
  await expect(trigger).toBeFocused()
  await trigger.click()
  await confirmation.getByRole('button', { name: 'Archivar cuenta', exact: true }).click()
  await expect(confirmation.getByRole('button', { name: 'Cancelar', exact: true })).toBeDisabled()
  await expect(confirmation.locator('.form-close')).toBeDisabled()
  await page.keyboard.press('Escape')
  await expect(confirmation).toBeVisible()
  release()
  await expect(confirmation).toHaveCount(0)
})

