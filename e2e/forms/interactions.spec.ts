test('budget total changes live, removes rows and never enters the save payload', async ({ page }) => {
  await mockAPI(page)
  await page.goto('/ui-exploration/forms-baseline/budget-edit')
  const hero = page.locator('[data-form-hero]')
  await expect(hero).toContainText('355.000')
  const inputs = page.locator('[data-task-scroll] input[inputmode="decimal"]')
  await inputs.first().fill('200.000')
  await expect(hero).toContainText('335.000')
  await page.getByRole('button', { name: 'Quitar', exact: true }).last().click()
  await expect(hero).toContainText('290.000')
  await inputs.first().fill('0')
  await expect(hero).toContainText('90.000')
  await page.getByRole('button', { name: 'Guardar presupuesto', exact: true }).click()
  await expect(page.locator('[data-task-footer] [role="alert"]')).toHaveText('Completá categoría y monto mayor a cero en todas las filas.')
  await expect(hero).toContainText('90.000')
  await inputs.first().fill('200.000')
  await page.getByRole('button', { name: 'Guardar presupuesto', exact: true }).click()
  await expect(page.locator('[data-task-surface]')).toHaveCount(0)
  expect(JSON.parse(await page.locator('[data-budget-saved]').textContent() ?? 'null')).toEqual([
    { id: 'fixture-item-0', category: 'Alimentación', amount: 200000 },
    { id: 'fixture-item-1', category: 'Transporte', amount: 90000 },
  ])
})

